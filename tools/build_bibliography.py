def get(url,accept=None):
    headers={"User-Agent":"SSTG-Nav-benchmark/1.0 (bibliography regeneration)"}
    if accept:headers["Accept"]=accept
    last=None
    for i in range(5):
        try:
            r=requests.get(url,headers=headers,timeout=60);r.raise_for_status();return r.text
        except Exception as e:last=e;time.sleep(2**i)
    raise last

def rekey(text,key):
    text=text.replace("â€“","--").replace("–","--")
    text=re.sub(r"month=([A-Za-z]+)",r"month={\1}",text)
    return re.sub(r"(@\w+\s*\{)[^,]+,",r"\g<1>"+key+",",text,count=1)

