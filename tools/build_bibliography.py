    # ArXiv-only and duplicate provenance entries are retained deliberately:
    # the *_arxiv keys let authors cite a preprint when the publisher record is inaccessible.
    for key,aid in ARXIV.items(): entries.append(rekey(get(f"https://export.arxiv.org/bibtex/{aid}").strip(),key))
    entries.extend(CVF_ENTRIES.values())
    header=("% Generated by tools/build_bibliography.py from DOI/Crossref and arXiv.\n"
            "% Do not copy the placeholder entries from SSTGNavPaper/reference.bib.\n\n")
    out=Path("paper/baselines.bib");out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(header+"\n\n".join(entries)+"\n")
    print(f"wrote {out}: {len(entries)} verified entries")
